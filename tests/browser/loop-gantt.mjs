import {settleMotion} from '../helpers/settle-motion.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';
import {fileURLToPath} from 'node:url';

test('Edge：第四种任务视图复用任务详情并保持周一开头的时间轴',async()=>{
  const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/#/collab?evaProject=prod&evaTab=tasks`);
    await settleMotion(page);
    await page.locator('.eva-task-view-menu').click();
    const ganttOption=page.locator('.eva-task-enum-menu:visible').getByText('甘特图',{exact:true});
    assert.equal(await ganttOption.count(),1,'第四个视图入口存在');
    await ganttOption.click();
    const view=page.locator('.eva-task-gantt');await view.waitFor();
    assert.equal(await view.locator('[data-weekday]').first().getAttribute('data-weekday'),'1');
    await settleMotion(page);
    const todayFrame=await view.locator('.eva-task-gantt__scroll').boundingBox();
    const todayColumn=await view.locator('.eva-task-gantt__column.is-today').boundingBox();
    assert.ok(Math.abs(todayColumn.x-(todayFrame.x+360+(todayFrame.width-360)/2-60))<2,'默认今天近时间区中心，保留前后日期上下文');
    const first=view.locator('.eva-task-gantt__task').first();
    const identifier=await first.locator('.eva-task-gantt__identifier').textContent();
    const locate=view.getByRole('button',{name:'定位 '+identifier,exact:true});
    assert.equal(await locate.count(),1,'视口外的任务提供定位入口');
    await locate.click();
    const visibleBar=view.locator('.eva-task-gantt__row').first().locator('.eva-task-gantt__bar');
    const bounds=await visibleBar.boundingBox(),frame=await view.locator('.eva-task-gantt__scroll').boundingBox();
    assert.ok(bounds.x>=frame.x+360&&bounds.x+bounds.width<=frame.x+frame.width,'定位后任务条完整进入时间轴');
    const barTitle=visibleBar.locator('.eva-task-gantt__bar-title');
    await page.waitForFunction(()=>{const bar=document.querySelector('.eva-task-gantt__row .eva-task-gantt__bar');return bar&&bar.querySelector('.eva-task-gantt__bar-text').getBoundingClientRect().left-bar.getBoundingClientRect().left<24;});
    const titleBounds=await barTitle.locator('.eva-task-gantt__bar-text').boundingBox();
    assert.ok(titleBounds.x-bounds.x<24,'可见任务条的标题从起点附近开始，不被错误sticky偏移推到右侧');
    await barTitle.hover();
    const preview=page.locator('.eva-task-preview');await preview.waitFor();
    assert.equal(await preview.locator('.eva-task-preview__title').textContent(),await first.locator('.eva-task-gantt__name').textContent());
    assert.ok((await preview.textContent()).includes('2026-09-07'));
    await page.keyboard.press('Escape');await preview.waitFor({state:'hidden'});
    await page.mouse.move(0,0);
    await barTitle.focus();await preview.waitFor();
    await page.keyboard.press('Escape');await preview.waitFor({state:'hidden'});
    await first.click();
    const detail=page.locator('.eva-task-outlet [role="dialog"]');await detail.waitFor();
    assert.ok((await detail.textContent()).includes(identifier));
    await page.keyboard.press('Escape');
    await detail.waitFor({state:'hidden'});
    assert.equal(await first.evaluate(node=>node===document.activeElement||node.contains(document.activeElement)),true);
    const normalBounds=await view.boundingBox();
    await view.getByRole('button',{name:'全屏',exact:true}).click();
    const fullscreenBounds=await view.boundingBox();
    const titlebar=await page.locator('.app-titlebar').boundingBox();
    assert.ok(fullscreenBounds.y>=titlebar.y+titlebar.height,'甘特全屏不覆盖客户端标题栏');
    assert.ok(fullscreenBounds.height>=normalBounds.height,'全屏使用任务内容宿主');
    await first.click();await detail.waitFor();await settleMotion(page);
    assert.equal(await detail.evaluate(node=>{const rect=node.getBoundingClientRect();return node.contains(document.elementFromPoint(rect.left+rect.width/2,rect.top+24));}),true,'任务详情在甘特全屏之上可操作');
    await page.keyboard.press('Escape');await detail.waitFor({state:'hidden'});
    assert.equal(await view.getByRole('button',{name:'退出全屏',exact:true}).count(),1,'关闭详情不退出下层甘特全屏');
    await page.keyboard.press('Escape');
    await view.getByRole('button',{name:'全屏',exact:true}).waitFor();
    assert.equal(await first.evaluate(node=>document.activeElement===node),true,'退出全屏保留原任务焦点');
    const axisTop=await view.locator('.eva-task-gantt__header').evaluate(node=>node.getBoundingClientRect().top);
    const originalDates=await barTitle.getAttribute('aria-label');
    await view.getByRole('button',{name:'编辑 '+identifier+' 的日期',exact:true}).click();
    const dateEditor=page.getByRole('dialog',{name:'任务日期'});
    await dateEditor.getByRole('button',{name:'截止日期',exact:true}).click();
    await page.getByRole('gridcell',{name:'2026-09-01',exact:true}).click();
    await page.getByText('开始日期不能晚于截止日期',{exact:true}).waitFor();
    assert.equal(await barTitle.getAttribute('aria-label'),originalDates,'错误日期不改变任务条');
    assert.equal(await view.locator('.eva-task-gantt__header').evaluate(node=>node.getBoundingClientRect().top),axisTop,'错误提示不挤动时间轴');
    await page.keyboard.press('Escape');await dateEditor.waitFor({state:'hidden'});
    const centerDateOffset=async width=>{
      const viewport=await view.locator('.eva-task-gantt__scroll').boundingBox(),task=await visibleBar.boundingBox();
      return (viewport.x+360+(viewport.width-360)/2-task.x)/width;
    };
    const weekCenter=await centerDateOffset(60);
    await view.getByRole('button',{name:'月',exact:true}).click();
    await settleMotion(page);
    assert.ok(Math.abs(await centerDateOffset(20)-weekCenter)<0.06,'周切月保留可视中心日期');
    assert.equal(await view.getByRole('button',{name:'月',exact:true}).getAttribute('aria-pressed'),'true');
    const monthColumns=view.locator('.eva-task-gantt__day');
    assert.equal(await monthColumns.first().getAttribute('data-unit'),'week','月视图按周画列');
    assert.equal(Math.round((await monthColumns.first().boundingBox()).width),140,'一周为7个自然日');
    await view.getByRole('button',{name:'季度',exact:true}).click();
    await settleMotion(page);
    assert.ok(Math.abs(await centerDateOffset(5)-weekCenter)<0.21,'月切季度保留可视中心日期，容许一个像素取整');
    const quarterColumns=view.locator('.eva-task-gantt__day');
    assert.equal(await quarterColumns.first().getAttribute('data-unit'),'month','季度视图按月画列');
    await page.waitForFunction(()=>{const column=document.querySelector('.eva-task-gantt__day[data-unit="month"]');return column?.getBoundingClientRect().width>=140;});
    assert.ok(await quarterColumns.first().evaluate(node=>node.getBoundingClientRect().width)>=140,'月份不压缩成5px每日网格');
    assert.ok(await view.locator('.eva-task-gantt__period-number').getByText(/^Q[1-4]$/).count());
    await view.locator('.eva-task-gantt__column.is-today').waitFor();
    assert.ok(await view.locator('.eva-task-gantt__bar.is-compact').count(),'季度保留真实短条');
    const fragments=await view.locator('.eva-task-gantt__bar.is-compact .eva-task-gantt__bar-text').evaluateAll(nodes=>nodes.filter(node=>getComputedStyle(node).visibility!=='hidden').length);
    assert.equal(fragments,0,'窄于可读阈值的短条不显示单字或半字碎片，完整标题仍在任务名和预览');
    // Keyboard scheduling of an existing unscheduled task uses the selected
    // timeline day and the quarter's inclusive eight-day span.
    const unscheduled=view.locator('[data-task-id="supply-29"]');
    await unscheduled.locator('.eva-task-gantt__task').scrollIntoViewIfNeeded();
    const schedule=unscheduled.locator('.eva-task-gantt__schedule');
    await schedule.focus();
    const before=(await schedule.getAttribute('aria-label')).match(/\d{4}-\d{2}-\d{2}/)[0];
    await schedule.press('ArrowRight');await schedule.press('ArrowRight');
    const selected=(await schedule.getAttribute('aria-label')).match(/\d{4}-\d{2}-\d{2}/)[0];
    assert.equal((Date.parse(selected)-Date.parse(before))/86400000,2,'方向键按自然日移动');
    const due=new Date(Date.parse(selected)+7*86400000).toISOString().slice(0,10);
    const savedViewport=await view.locator('.eva-task-gantt__scroll').evaluate(node=>({left:node.scrollLeft,top:node.scrollTop}));
    await schedule.press('Enter');
    const newBar=unscheduled.locator('.eva-task-gantt__bar-title');await newBar.waitFor();
    assert.ok((await newBar.getAttribute('aria-label')).endsWith(selected+' 至 '+due));
    assert.equal(await newBar.evaluate(node=>document.activeElement===node),true,'保存后焦点转移到同一任务条: '+await page.evaluate(()=>document.activeElement.outerHTML.slice(0,400)));
    assert.equal(await view.getByRole('button',{name:'季度',exact:true}).getAttribute('aria-pressed'),'true','更新任务不重置尺度');
    assert.deepEqual(await view.locator('.eva-task-gantt__scroll').evaluate(node=>({left:node.scrollLeft,top:node.scrollTop})),savedViewport,'更新任务不重置横纵滚动位置');
    const savedTaskBox=await newBar.boundingBox();
    await page.keyboard.press('Escape');
    await settleMotion(page);
    await page.locator('.eva-task-view-menu').click();
    await page.locator('.eva-task-enum-menu:visible').getByText('表格',{exact:true}).click();
    const tableRow=page.locator('.eva-task-table__row').filter({hasText:'SC-129'});
    await tableRow.waitFor();
    assert.equal(await tableRow.getByRole('button',{name:'截止日期',exact:true}).getAttribute('data-eva-tooltip'),'截止日期 '+due,'表格读取同一次写入的截止日期');
    await settleMotion(page);
    await page.locator('.eva-task-view-menu').click();
    await page.locator('.eva-task-enum-menu:visible').getByText('甘特图',{exact:true}).click();
    const returned=view.locator('[data-task-id="supply-29"]');
    assert.ok((await returned.locator('.eva-task-gantt__bar-title').getAttribute('aria-label')).endsWith(selected+' 至 '+due),'往返切换不丢失排期');
    await settleMotion(page);
    assert.equal(await view.getByRole('button',{name:'季度',exact:true}).getAttribute('aria-pressed'),'true','视图往返恢复季度尺度');
    let restoredBox=await returned.locator('.eva-task-gantt__bar-title').boundingBox();
    assert.ok(Math.abs(restoredBox.x-savedTaskBox.x)<=1&&Math.abs(restoredBox.y-savedTaskBox.y)<=1,'视图往返按日期和任务ID恢复浏览位置');
    await page.getByText('我负责的',{exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.eva-task-gantt__toolbar button[aria-pressed="true"]')?.textContent==='周');
    assert.equal(await view.locator('[data-task-id="supply-29"]').count(),0,'筛选后的集合不沿用旧任务');
    await page.getByText('全部任务',{exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.eva-task-gantt__toolbar button[aria-pressed="true"]')?.textContent==='季度');
    await settleMotion(page);
    restoredBox=await returned.locator('.eva-task-gantt__bar-title').boundingBox();
    assert.ok(Math.abs(restoredBox.x-savedTaskBox.x)<=1&&Math.abs(restoredBox.y-savedTaskBox.y)<=1,'返回相同筛选恢复该上下文位置');
    await view.getByRole('button',{name:'周',exact:true}).click();await settleMotion(page);

    // Prepending earlier dates must keep existing bars at the same screen position.
    const timeline=view.locator('.eva-task-gantt__scroll');
    const canvas=view.locator('.eva-task-gantt__canvas');
    const oldWidth=await canvas.evaluate(node=>node.getBoundingClientRect().width);
    const reference=view.locator('[data-task-id="supply-1"] .eva-task-gantt__bar');
    await timeline.evaluate(node=>{node.scrollTop=0;node.scrollLeft=600;});
    await page.waitForFunction(width=>document.querySelector('.eva-task-gantt__canvas').getBoundingClientRect().width>width,oldWidth);
    const afterWidth=await canvas.evaluate(node=>node.getBoundingClientRect().width);
    const actualLeft=await timeline.evaluate(node=>node.scrollLeft);
    assert.equal(actualLeft,600+afterWidth-oldWidth,'向左新增日期的宽度完整补偿到滚动位置');
    assert.equal(await reference.count(),1,'延展不丢失现有任务');
    // Both coarser scales also compensate by their own day width, not week pixels.
    for(const label of ['月','季度']){
      await view.getByRole('button',{name:label,exact:true}).click();
      await page.waitForFunction(()=>document.querySelector('.eva-task-gantt__scroll').scrollLeft>600);
      const width=await canvas.evaluate(node=>node.getBoundingClientRect().width);
      await timeline.evaluate(node=>{node.scrollLeft=600;});
      await page.waitForFunction(previous=>document.querySelector('.eva-task-gantt__canvas').getBoundingClientRect().width>previous,width);
      const grown=await canvas.evaluate(node=>node.getBoundingClientRect().width);
      assert.equal(await timeline.evaluate(node=>node.scrollLeft),600+grown-width,label+'延展保持相同日期位置');
    }
    assert.deepEqual(errors,[]);
  }finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
});
