import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';

test('分类往返保留跨类选择，整行可选，头像和文字居中',async()=>{
 const server=createServer(new URL('../../dist',import.meta.url).pathname);
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
 try{
  const context=await browser.newContext({viewport:{width:1200,height:800}});
  await context.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin+'/#/messages');
  await page.getByRole('button',{name:'新建',exact:true}).click();
  await page.getByRole('menuitem',{name:'新建群聊',exact:true}).click();
  const dialog=page.getByRole('dialog'),left=dialog.locator('.eva-member-picker__available'),selected=dialog.locator('.eva-member-picker__selected-item');
  await dialog.waitFor();
  assert.equal(await selected.count(),1);
  const searchBox=left.getByRole('textbox',{name:'搜索可选成员'});
  await searchBox.fill('王宜林');
  assert.equal(await left.locator('.eva-member-picker__candidate-group-head').count(),0,'全局搜索结果不分组');
  assert.equal(await left.locator('.eva-member-picker__candidate-flat').count(),1,'全局搜索只有一个平铺列表');
  assert.equal(await left.getByRole('button',{name:/^联系人/}).count(),0,'搜索时不显示分类入口');
  assert.ok(await left.locator('.eva-member-picker__candidate').count()>0);
  await searchBox.fill('');
  const cloneHeader=left.getByRole('button',{name:/^我的 AI 分身/});
  assert.equal(await left.locator('.eva-member-picker__candidate').count(),0,'首页只呈现分类');
  assert.equal(await cloneHeader.getByText('已全选',{exact:true}).count(),1);
  await cloneHeader.click();
  const toolbarBounds=await left.evaluate(el=>{const panel=el.getBoundingClientRect(),bar=el.querySelector('.eva-member-picker__category-toolbar'),button=bar.querySelector('button').getBoundingClientRect(),nav=bar.querySelector('nav').getBoundingClientRect();return {inside:button.right<=panel.right,apart:nav.right<=button.left};});
  assert.deepEqual(toolbarBounds,{inside:true,apart:true},'面包屑可收缩并为取消全选保留左栏内空间');
  await page.screenshot({path:'/tmp/eva-picker-toolbar-fit.png',animations:'disabled'});

  assert.equal(await left.getByText('仅可添加自己的 AI 分身',{exact:true}).count(),1);
  assert.equal(await left.locator('.eva-member-picker__candidate').first().getByRole('checkbox').isChecked(),true);
  await left.getByRole('link',{name:'全部'}).click();
  assert.equal(await selected.count(),1);
  assert.equal(await left.getByRole('button',{name:/^联系人/}).count(),1,'联系人应为进入分类的按钮');
  const categoryRow=left.getByRole('button',{name:'联系人',exact:true});
  assert.equal(await categoryRow.locator('.lucide-book-user').count(),1,'分类复用公共 Lucide 图标');
  await categoryRow.hover();
  await page.screenshot({path:'/tmp/eva-member-picker-redo-home-hover.png'});
  const categoryBox=await categoryRow.boundingBox();
  await categoryRow.click({position:{x:categoryBox.width-6,y:categoryBox.height/2}});
  assert.equal(await selected.count(),1,'进入分类不清空已选分身');
  const row=left.locator('.eva-member-picker__candidate').first();
  await row.locator('.semi-checkbox-inner-display').click();
  assert.equal(await row.getByRole('checkbox').isChecked(),true);
  assert.equal(await selected.count(),2,'直接点复选框只切换一次');
  await row.getByRole('checkbox').press('Space');
  assert.equal(await row.getByRole('checkbox').isChecked(),false);
  const box=await row.boundingBox();await row.click({position:{x:box.width-5,y:box.height/2}});
  assert.equal(await selected.count(),2,'姓名右侧空白也能选择');
  const geometry=await row.evaluate(el=>{const a=el.querySelector('.eva-members-human-avatar').getBoundingClientRect(),r=el.getBoundingClientRect();return {size:[a.width,a.height],delta:Math.abs(a.y+a.height/2-r.y-r.height/2)};});
  assert.deepEqual(geometry.size,[28,28]);assert.ok(geometry.delta<1);
  await left.getByRole('link',{name:'全部'}).click();
  assert.equal(await selected.count(),2);
  await left.getByRole('button',{name:'联系人 已选 1',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/eva-picker-selection-status.png',animations:'disabled'});
  assert.equal(await left.getByRole('button',{name:/^数字员工/}).count(),1,'无可选项也保留分类入口');
  await dialog.getByRole('button',{name:'清空',exact:true}).click();
  await left.getByRole('button',{name:'我的 AI 分身',exact:true}).waitFor();
  await left.getByRole('button',{name:'联系人',exact:true}).waitFor();
  await left.getByRole('button',{name:/^联系人/}).click();
  await searchBox.fill('AI');
  assert.equal(await left.locator('.eva-member-picker__candidate .ai-badge').count(),0,'联系人内搜索不会返回其他分类的 AI');
  assert.equal(await left.locator('.eva-member-picker__candidate-group-head').count(),0);
  await searchBox.fill('');

  assert.equal(await left.getByRole('checkbox',{name:'全选',exact:true}).count(),0,'全选使用面包屑旁的文字按钮');
  await left.getByRole('button',{name:'全选',exact:true}).click();
  assert.equal(await selected.count(),300,'全选覆盖全部 300 个联系人');
  await left.getByRole('button',{name:'取消全选',exact:true}).click();
  assert.equal(await selected.count(),0);

  await left.locator('.eva-member-picker__candidate').first().click();
  assert.equal(await selected.count(),1);
  await left.getByRole('link',{name:'全部'}).click();
  await left.getByRole('button',{name:/^我的 AI 分身/}).click();
  assert.equal(await left.getByRole('checkbox',{name:/选择.*AI 分身/}).isChecked(),false,'分类切换不会重新勾选分身');
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await page.getByRole('button',{name:'新建',exact:true}).click();
  await page.getByRole('menuitem',{name:'新建群聊',exact:true}).click();
  assert.equal(await selected.count(),1);assert.equal(await left.getByRole('button',{name:/^联系人/}).count(),1);
  await page.setViewportSize({width:760,height:640});
  await left.getByRole('button',{name:/^联系人/}).click();
  const bounds=await left.evaluate(el=>{const l=el.getBoundingClientRect(),b=el.querySelector('nav').getBoundingClientRect();return {left:b.left>=l.left,right:b.right<=l.right,top:b.top>=l.top};});
  assert.deepEqual(bounds,{left:true,right:true,top:true},'窄窗口面包屑仍在左栏内');
  assert.equal(await selected.count(),1);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await page.setViewportSize({width:1200,height:800});
  await page.goto(origin+'/#/collab?evaProject=prod&evaTab=settings');
  await page.getByRole('tab',{name:'成员管理',exact:true}).click();
  await page.getByRole('button',{name:'添加成员',exact:true}).click();
  const joinedClone=left.getByRole('button',{name:'我的 AI 分身 已全部添加',exact:true});
  await joinedClone.waitFor();
  assert.equal(await left.getByRole('button',{name:/^(我的 AI 分身|联系人|数字员工)/}).count(),3);
  assert.equal(await joinedClone.locator('.semi-tag').count(),0,'状态使用辅助文字而非 Tag');
  await page.screenshot({path:'/tmp/eva-picker-all-categories.png',animations:'disabled'});
  await joinedClone.click();
  const joinedRow=left.locator('.eva-member-picker__candidate');
  assert.equal(await joinedRow.count(),1);
  assert.equal(await joinedRow.getByRole('checkbox').isChecked(),true);
  assert.equal(await joinedRow.getByRole('checkbox').isDisabled(),true);
  await joinedRow.click();
  assert.equal(await selected.count(),0,'已添加条目不可重复选择');
  await page.screenshot({path:'/tmp/eva-picker-joined-clone.png',animations:'disabled'});
  await left.getByRole('link',{name:'全部'}).click();
  await left.getByRole('button',{name:/^联系人/}).click();
  const candidates=left.locator('.eva-member-picker__candidate');
  const rowSnapshot=()=>candidates.evaluateAll(nodes=>nodes.map(node=>({name:node.querySelector('input').getAttribute('aria-label'),joined:node.getAttribute('aria-disabled')==='true'})));
  const before=await rowSnapshot();
  const firstJoined=before.findIndex(row=>row.joined);
  assert.ok(firstJoined>0&&firstJoined<before.length,'同时包含可添加和已添加成员');
  assert.ok(before.slice(firstJoined).every(row=>row.joined),'已添加成员统一位于末尾');
  await candidates.first().click();
  assert.deepEqual(await rowSnapshot(),before,'本次勾选不改变列表顺序');
  await left.getByRole('textbox',{name:'搜索可选成员'}).fill('周');
  const searched=await rowSnapshot();
  assert.ok(searched.some(row=>row.joined),'搜索保留已添加成员');
  const joinedIndex=searched.findIndex(row=>row.joined);
  assert.ok(searched.slice(joinedIndex).every(row=>row.joined),'搜索结果仍将已添加排后');
  await left.getByRole('textbox',{name:'搜索可选成员'}).fill('');
  assert.deepEqual(await rowSnapshot(),before,'清除搜索恢复原有稳定顺序');
  await page.screenshot({path:'/tmp/eva-picker-available-first.png',animations:'disabled'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(r=>server.close(r));}
});
