import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';

test('项目数字员工目录：业务域、勾选、取消、保存和已添加状态',async()=>{
 const server=createServer(new URL('../../dist',import.meta.url).pathname);
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
 try{
  const page=await browser.newPage({viewport:{width:1200,height:800}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
  await page.goto(origin+'/#/collab?evaProject=prod&evaTab=settings');
  await page.getByRole('tab',{name:'成员管理',exact:true}).click();
  async function open(){await page.getByRole('button',{name:'添加成员',exact:true}).click();await page.getByRole('dialog',{name:'添加项目成员',exact:true}).getByRole('button',{name:'数字员工',exact:true}).click();}
  await open();
  const dialog=page.getByRole('dialog',{name:'添加项目成员',exact:true}),rows=dialog.locator('.eva-member-picker__candidate');
  assert.ok(await rows.count()>0);
  assert.equal(await dialog.getByRole('checkbox',{name:'选择HR 入职服务专家',exact:true}).isDisabled(),true);
  assert.equal(await rows.first().locator('.ai-badge').count(),1);
  assert.match(await dialog.getByRole('combobox',{name:'数字员工业务域'}).innerText(),new RegExp('全部业务域 '+await rows.count()+'$'),'总数包含已添加员工');
  await dialog.getByRole('combobox',{name:'数字员工业务域'}).click();
  await page.getByRole('option',{name:/^供应链 \d+$/}).click();
  await dialog.getByRole('combobox',{name:'数字员工业务域'}).getByText(/^供应链 \d+$/).waitFor();
  const domainNames=await rows.locator('.eva-identity-name-text').allTextContents();
  assert.ok(domainNames.length>0);
  const expected=await page.evaluate(()=>window.EvaDigitalEmployeesStore.agents().filter(a=>a.kind==='staff'&&a.domain==='供应链').map(a=>a.name));
  assert.ok(domainNames.every(name=>expected.includes(name)));
  await page.screenshot({path:'/tmp/eva-project-employee-domain.png'});
  const choice=rows.getByRole('checkbox').first(),label=await choice.getAttribute('aria-label'),name=label.slice(2);
  await rows.first().locator('.semi-checkbox-inner-display').click();
  assert.equal(await dialog.locator('.eva-member-picker__selected-item').filter({hasText:name}).count(),1);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await open();
  const target=dialog.getByRole('checkbox',{name:'选择'+name,exact:true});
  assert.equal(await target.isChecked(),false,'取消不保存');
  await rows.filter({has:page.getByRole('checkbox',{name:'选择'+name,exact:true})}).locator('.semi-checkbox-inner-display').click();
  await dialog.getByRole('button',{name:'确认添加',exact:true}).click();
  await open();
  assert.equal(await target.isDisabled(),true);
  assert.equal(await target.isChecked(),true);
  assert.equal(await dialog.locator('.eva-member-picker__selected-item').count(),0,'已有成员不重复放进本次选择');
  await page.screenshot({path:'/tmp/eva-project-employee-selected.png'});
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await page.goto(origin+'/#/collab');
  await page.getByRole('button',{name:'新建项目',exact:true}).click();
  const create=page.getByRole('dialog',{name:'新建项目',exact:true});
  await create.locator('#eva-project-name').fill('数字员工项目验收');
  await create.getByRole('button',{name:'清空',exact:true}).click();
  await create.getByRole('button',{name:'数字员工',exact:true}).click();
  await create.getByRole('textbox',{name:'搜索可选成员'}).fill(name);
  await create.locator('.eva-member-picker__candidate').filter({has:page.getByRole('checkbox',{name:'选择'+name,exact:true})}).click();
  await create.getByRole('button',{name:'创建并进入项目',exact:true}).click();
  await create.waitFor({state:'hidden'});
  const created=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('eva:project-members:v1')).projects).find(project=>project.name==='数字员工项目验收'));
  assert.equal(created.employeeIds.length,1,'新建项目一并保存选中的数字员工');
  await page.goto(origin+'/#/messages');
  await page.getByRole('button',{name:'新建',exact:true}).click();
  await page.getByRole('menuitem',{name:'新建群聊',exact:true}).click();
  const group=page.getByRole('dialog',{name:'新建群聊',exact:true});
  await group.getByLabel('群聊名称',{exact:true}).fill('数字员工群聊验收');
  await group.getByRole('button',{name:'数字员工',exact:true}).click();
  assert.ok(await group.locator('.eva-member-picker__candidate').count()>0,'群聊具有数字员工候选');
  await group.getByRole('textbox',{name:'搜索可选成员'}).fill(name);
  await group.getByRole('button',{name:'全选',exact:true}).click();
  assert.equal(await group.locator('.eva-member-picker__selected-item').count(),2,'只选筛选出的员工并保留分身');
  await group.getByRole('button',{name:'取消全选',exact:true}).click();
  assert.equal(await group.locator('.eva-member-picker__selected-item').count(),1,'取消全选保留其他分类');
  await group.getByRole('button',{name:'全选',exact:true}).click();
  await page.screenshot({path:'/tmp/eva-group-employee-select.png',animations:'disabled'});
  await group.getByRole('button',{name:'创建群聊',exact:true}).click();
  await group.waitFor({state:'hidden'});
  const savedGroup=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('eva:project-members:v1')).groups).find(g=>g.name==='数字员工群聊验收'));
  assert.equal(savedGroup.employeeIds.length,1,'创建群聊保存数字员工');
  assert.equal(savedGroup.employeeIds[0],created.employeeIds[0]);
  assert.deepEqual(errors,[]);

 }finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
});
