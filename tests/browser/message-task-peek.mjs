test('主动进入所属项目、直接链接与归档只读保持各自边界',async()=>{
 const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const origin=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch({channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1000}}),errors=[];page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(10000);
  await page.goto(origin+'/#/messages');await page.locator('[data-eva-task-link="CLIENT-103"]').first().click();
  await page.locator('.loop-idp__title:visible').waitFor();
  await page.locator('.eva-task-breadcrumb-item:visible').filter({hasText:'客户联合交付'}).first().click();
  await page.waitForURL(/evaProject=lab.*evaTask=client-103/);
  await page.locator('.loop-idp__title:visible').waitFor();
  assert.equal(await page.locator('[data-eva-project-id]').getAttribute('data-eva-project-id'),'lab');
  // Navigating while the previous detail is open must not consume the new deep link.
  await page.goto(origin+'/#/collab?evaProject=prod&evaTab=tasks&evaTask=SC-103');
  await page.waitForFunction(()=>document.querySelector('.loop-idp__title')?.value==='处理关键供应商来料质量异常');
  await page.getByRole('button',{name:'关闭任务详情',exact:true}).click();
  assert.equal(new URL(page.url()).hash,'#/collab?evaProject=prod&evaTab=tasks');
  await page.goto(origin+'/#/collab?evaProject=prod&evaTab=channels');
  await page.locator('[data-eva-task-link="CLIENT-103"]').first().click();await page.locator('.loop-idp__title:visible').waitFor();
  await page.evaluate(()=>{const s=window.__evaGetFileContext().store;s.setProjectArchived('prod',s.actorId(),true);});
  assert.equal(await page.locator('.loop-idp__title:visible').isEditable(),true,'来源项目归档不冻结另一项目的任务');
  await page.getByRole('button',{name:'关闭任务详情',exact:true}).click();
  await page.evaluate(()=>{const s=window.__evaGetFileContext().store,actor=s.actorId(),owner=s.projectRecord('lab').ownerId;s.setActor(owner);s.setProjectArchived('lab',owner,true);s.setActor(actor);});
  await page.locator('[data-eva-task-link="CLIENT-103"]').first().click();await page.locator('.loop-idp__title:visible').waitFor();
  assert.equal(await page.locator('.loop-idp__title:visible').isEditable(),false,'目标任务项目归档后详情只读');
  assert.equal(await page.locator('.loop-idp__newcomment:visible').count(),0);
  assert.equal(await page.getByRole('button',{name:'添加子任务',exact:true}).count(),0);
  await page.evaluate(()=>window.__evaGetFileContext().store.setActor('u-zhouyuan'));
  await page.locator('.eva-task-detail-host').waitFor({state:'hidden'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(r=>server.close(r));}
});

