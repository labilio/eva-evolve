import assert from 'node:assert/strict';
import {settleMotion} from '../helpers/settle-motion.mjs';
import {test} from 'node:test';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';
import {fileURLToPath} from 'node:url';

test('父任务：单层搜索、即时关联、移除、取消与项目隔离',async()=>{
 const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
 const page=await browser.newPage({viewport:{width:1200,height:800}}),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
 page.setDefaultTimeout(10000);
 const more=()=>page.getByRole('button',{name:'更多操作',exact:true});
 const open=async()=>{await more().click();await settleMotion(page);await page.locator('.semi-dropdown-menu:visible').getByRole('menuitem',{name:'关联父任务',exact:true}).click();return page.getByRole('dialog',{name:'关联父任务',exact:true});};
 try{
  await page.goto(origin+'/#/collab?evaProject=prod&evaTab=tasks&evaTask=SC-103');
  let picker=await open();await picker.waitFor();
  assert.equal(await picker.locator('.semi-select').count(),0,'任务搜索不再嵌套 Select');
  assert.equal(await picker.getByRole('button',{name:'保存',exact:true}).count(),0);
  let input=picker.getByRole('textbox',{name:'搜索任务编号或标题'});
  const defaultRows=await picker.getByRole('option').allTextContents();
  assert.ok(defaultRows.length>20,'空搜索直接提供当前项目候选，不要求先输入');
  assert.ok(defaultRows.every(text=>text.includes('SC-')&&!text.includes('SC-103')));
  await input.fill('不存在的父任务');await picker.getByText('没有匹配的任务',{exact:true}).waitFor();
  await input.fill('');assert.deepEqual(await picker.getByRole('option').allTextContents(),defaultRows,'清空恢复默认候选和顺序');
  await input.fill('SC-103');await picker.getByText('没有匹配的任务',{exact:true}).waitFor();
  await input.fill('EVA-');await picker.getByText('没有匹配的任务',{exact:true}).waitFor();
  await input.fill('SC-105');
  const option=picker.getByRole('option').filter({hasText:'SC-105'});await option.waitFor();
  assert.equal(await option.locator('svg').count(),1,'结果复用任务状态图标');
  await option.click();await picker.waitFor({state:'hidden'});
  await more().click();await page.getByRole('menuitem',{name:'移除父任务',exact:true}).waitFor();
  await page.getByRole('menuitem',{name:'移除父任务',exact:true}).click();
  await more().click();assert.equal(await page.getByRole('menuitem',{name:'移除父任务',exact:true}).count(),0);
  await more().click();await settleMotion(page);
  picker=await open();input=picker.getByRole('textbox',{name:'搜索任务编号或标题'});
  await input.fill('SC-105');await input.press('Escape');await picker.waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='更多操作');
  picker=await open();input=picker.getByRole('textbox',{name:'搜索任务编号或标题'});
  assert.equal(await input.inputValue(),'','重开清空搜索');
  await input.fill('齐套风险');await picker.getByRole('option').filter({hasText:'SC-105'}).waitFor();
  await input.press('ArrowDown');await input.press('Enter');await picker.waitFor({state:'hidden'});
  assert.equal(await page.locator('.loop-idp__title:visible').inputValue(),'处理关键供应商来料质量异常','关联不跳转任务');
  await page.locator('.loop-idp__parent-link:visible').click();
  picker=await open();input=picker.getByRole('textbox',{name:'搜索任务编号或标题'});
  await input.fill('SC-103');await picker.getByText('没有匹配的任务',{exact:true}).waitFor();
  await input.fill('');
  assert.ok(await picker.getByRole('option').count()>20);
  await settleMotion(page);
  const geometry=await picker.evaluate(el=>{const row=el.querySelector('[role="option"]'),label=row.querySelector('.eva-parent-task-picker__identifier'),title=row.querySelector('.eva-parent-task-picker__title'),input=el.querySelector('.semi-input-wrapper');return {gap:title.getBoundingClientRect().left-label.getBoundingClientRect().right,height:input.getBoundingClientRect().height,top:el.getBoundingClientRect().top};});
  assert.equal(geometry.gap,8);assert.equal(geometry.height,32);assert.ok(geometry.top>36);
  await mkdir(new URL('../../artifacts/parent-task-picker/',import.meta.url),{recursive:true});
  await Promise.all((await page.getByText('已保存',{exact:true}).all()).map(toast=>toast.waitFor({state:'hidden'})));
  await page.screenshot({path:new URL('../../artifacts/parent-task-picker/desktop.png',import.meta.url).pathname});
  await page.setViewportSize({width:640,height:600});
  await input.fill('SC-135');await picker.getByRole('option').waitFor();
  assert.equal(await picker.evaluate(el=>el.scrollWidth<=el.clientWidth),true,'窄窗口长标题不撑破弹窗');
  await input.dispatchEvent('keydown',{key:'Enter',code:'Enter',isComposing:true});
  assert.equal(await picker.isVisible(),true,'输入法确认不关联');
  await input.press('Escape');await picker.waitFor({state:'hidden'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
});
