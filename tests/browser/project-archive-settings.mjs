import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';
import {fileURLToPath} from 'node:url';

test('设置管理归档项目：搜索、取消、恢复、删除、权限及刷新',async()=>{
 const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin+'/#/collab');await page.locator('.eva-project-directory').waitFor();
  await page.evaluate(()=>{const {store}=window.__evaGetFileContext();store.setProjectArchived('drive-design',store.actorId(),true);});
  assert.equal(await page.locator('.eva-project-directory').getByText('已归档项目',{exact:true}).count(),0);
  assert.equal(await page.locator('.eva-project-directory').getByText('团队文件功能设计',{exact:true}).count(),0);
  const open=async()=>{await page.getByRole('button',{name:'账户：王宜林'}).hover();await page.getByRole('menuitem',{name:'设置',exact:true}).click();await page.getByRole('button',{name:'数据管理',exact:true}).click();};
  await open();
  const section=page.getByRole('region',{name:'已归档项目'}),search=section.getByRole('textbox',{name:'搜索已归档项目'});
  await search.fill('没有这个项目');await page.getByText('没有匹配的已归档项目',{exact:true}).waitFor();await search.fill('团队文件');
  await section.getByRole('button',{name:'团队文件功能设计',exact:true}).waitFor();
  await page.screenshot({path:'/tmp/eva-archive-settings-light.png'});
  await section.getByRole('button',{name:'恢复项目',exact:true}).click();
  let dialog=page.getByRole('dialog',{name:'恢复项目',exact:true});await dialog.getByRole('button',{name:'恢复项目',exact:true}).click();await dialog.getByText('请输入“恢复项目”确认',{exact:true}).waitFor();
  await dialog.getByRole('textbox').fill('恢复项目');await dialog.getByRole('button',{name:'恢复项目',exact:true}).click();await dialog.waitFor({state:'hidden'});
  assert.equal(await section.getByRole('button',{name:'团队文件功能设计',exact:true}).count(),0);
  await page.getByRole('button',{name:'关闭设置'}).click();await page.locator('.eva-project-directory').getByText('团队文件功能设计',{exact:true}).first().waitFor();
  await page.goto(origin+'/#/collab?evaProject=drive-design&evaTab=channels');
  await page.locator('.wk-msg-system-tag-text').filter({hasText:'王宜林归档了项目'}).waitFor();
  await page.locator('.wk-msg-system-tag-text').filter({hasText:'王宜林恢复了项目'}).waitFor();
  await page.reload();
  await page.locator('.wk-msg-system-tag-text').filter({hasText:'王宜林恢复了项目'}).waitFor();
  await page.evaluate(()=>{const {store}=window.__evaGetFileContext();store.setProjectArchived('drive-design',store.actorId(),true);});
  await page.goto(origin+'/#/collab?evaProject=drive-design&evaTab=project-info');await page.locator('.collab-frame').waitFor();
  await open();await search.fill('');
  await section.getByRole('button',{name:'删除项目 团队文件功能设计',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'删除项目',exact:true});await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await section.getByRole('button',{name:'团队文件功能设计',exact:true}).waitFor();
  await section.getByRole('button',{name:'删除项目 团队文件功能设计',exact:true}).click();
  await dialog.getByRole('textbox').fill('错误名称');await dialog.getByRole('button',{name:'删除项目',exact:true}).click();await dialog.getByText('请输入完整项目名称确认',{exact:true}).waitFor();
  await dialog.getByRole('textbox').fill('团队文件功能设计');await dialog.getByRole('button',{name:'删除项目',exact:true}).click();await dialog.waitFor({state:'hidden'});
  await section.getByText('暂无已归档项目',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.__evaGetFileContext().store.isProjectDeleted('drive-design')),true);
  assert.equal(await page.evaluate(()=>window.EvaProjectReminderDemo.count('drive-design')),0);
  await page.getByRole('button',{name:'关闭设置'}).click();
  await page.goto(origin+'/#/collab');await page.locator('.eva-project-directory').waitFor();
  assert.equal(await page.locator('.eva-project-directory').getByText('团队文件功能设计',{exact:true}).count(),0);
  await page.reload();await page.locator('.eva-project-directory').waitFor();assert.equal(await page.evaluate(()=>window.EvaProjectReminderDemo.count('drive-design')),0);await open();await section.getByText('暂无已归档项目',{exact:true}).waitFor();
  await page.evaluate(()=>{const {store}=window.__evaGetFileContext();store.setActor('u-zhouyuan');store.setProjectArchived('zhou-private-review','u-zhouyuan',true);store.setActor('u-wangyilin');});
  assert.equal(await section.getByRole('button',{name:/方案评审/}).count(),0);
  await page.evaluate(()=>{const {store}=window.__evaGetFileContext();store.setProjectArchived('prod','u-wangyilin',true);store.setActor('u-linxiao');});
  assert.equal(await section.getByRole('button',{name:'恢复项目',exact:true}).count(),0);assert.equal(await section.getByRole('button',{name:/删除项目 /}).count(),0);
  await page.setViewportSize({width:1000,height:800});await page.evaluate(()=>window.EvaTheme.apply('dark'));await page.screenshot({path:'/tmp/eva-archive-settings-dark.png'});
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
});
