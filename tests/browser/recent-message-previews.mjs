import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';

const server = createServer(fileURLToPath(new URL('../../dist', import.meta.url)));
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch(process.platform === 'darwin' ? {channel: 'msedge'} : {});

try {
  const page = await browser.newPage({viewport: {width: 1200, height: 800}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/#/messages`);
  await page.evaluate(() => localStorage.removeItem('eva:project-members:v1'));
  await page.reload();
  await page.getByRole('button', {name: '最近', exact: true}).click();

  const group = page.locator('.wk-conversationlist-item').filter({has: page.getByRole('heading', {name: '产品共创交流群', exact: true})});
  await group.waitFor();
  assert.equal(await page.locator('.wk-conversationlist-item h3').filter({hasText: '近期体验反馈整理'}).count(), 0, '子区没有独立会话行');
  const purchasing = page.locator('.wk-conversationlist-item').filter({has: page.getByRole('heading', {name: '采购与招投标', exact: true})});
  assert.match(await purchasing.locator('.wk-conversationlist-item-indicators').innerText(), /16/, '群行汇总父群和子区未读');
  assert.match(await group.locator('.wk-conversationlist-item-lastmsg').innerText(), /近期体验反馈整理 · 周远的 AI 分身: 这是周远另一个项目里的任务/);
  await group.click();
  const tabs = page.getByRole('navigation', {name: '群聊子区'});
  assert.match(await tabs.innerText(), /主聊天/, '默认会话使用主聊天命名');
  await tabs.getByRole('tab', {name: '主聊天'}).waitFor();
  assert.equal(await tabs.locator('.semi-tabs-tab:first-child svg.lucide-message-circle').count(), 1, '主聊天有默认话题图标');
  assert.equal(await tabs.locator('[data-eva-tooltip]').count(), 0, '完整可见的导航名称不重复浮出提示');
  assert.equal(await tabs.locator('.semi-tabs').count(), 1, '群内导航复用 Semi Tabs');
  assert.equal(await tabs.locator('.eva-recent-topic-tabs__indicator').count(), 1, '仅一个随受控选中态移动的指示线');
  const divider = tabs.locator('.eva-recent-topic-tabs__divider');
  assert.equal(await divider.count(), 1, '主群与子区之间只有一条分隔线');
  assert.equal(await tabs.locator('.semi-tabs-tab:not(:first-child) svg.lucide-corner-down-right').count(), (await tabs.getByRole('tab').count()) - 1, '每个子区标签都有统一图标');
  await tabs.getByRole('tab', {name: '近期体验反馈整理'}).click();
  assert.match(await page.locator('.wk-chat-conversation-header-channel-info').innerText(), /产品共创交流群/);
  assert.doesNotMatch(await page.locator('.wk-chat-conversation-header-channel-info').innerText(), /近期体验反馈整理/, '群内切换保持群标题稳定');
  assert.match(await group.getAttribute('class'), /wk-conversationlist-item-selected/, '进入子区仍选中所属大群');
  await page.getByRole('textbox', {name: '发送给 近期体验反馈整理'}).fill('独立草稿验收');
  await tabs.getByRole('tab', {name: '主聊天'}).click();
  assert.equal(await tabs.getByRole('tab', {name: '主聊天'}).getAttribute('aria-selected'), 'true');
  assert.doesNotMatch(await page.getByRole('textbox', {name: '发送给 产品共创交流群'}).innerText(), /独立草稿验收/);
  await tabs.getByRole('tab', {name: '近期体验反馈整理'}).click();
  assert.match(await page.getByRole('textbox', {name: '发送给 近期体验反馈整理'}).innerText(), /独立草稿验收/, '群内切换恢复各自草稿');
  await page.getByRole('textbox', {name: '发送给 近期体验反馈整理'}).fill('');
  await page.getByRole('button', {name: '搜索会话'}).click();
  await page.getByRole('textbox', {name: '搜索群聊或子区'}).fill('近期体验反馈整理');
  const topicResult = page.locator('.wk-conversationlist-item').filter({has: page.getByRole('heading', {name: '产品共创交流群 / 近期体验反馈整理', exact: true})});
  await topicResult.waitFor();
  await topicResult.click();
  assert.equal(await tabs.getByRole('tab', {name: '近期体验反馈整理'}).getAttribute('aria-selected'), 'true', '搜索结果同步群内选中态');
  await page.getByRole('button', {name: '搜索会话'}).click();
  const editor = page.getByRole('textbox', {name: '发送给 近期体验反馈整理'});
  await editor.fill('最近聚合验收：子区新消息');
  await editor.press('Enter');
  await page.waitForFunction(() => document.querySelector('.wk-conversationlist-item h3')?.textContent === '采购与招投标' && document.querySelectorAll('.wk-conversationlist-item h3')[1]?.textContent === '产品共创交流群');
  assert.match(await group.locator('.wk-conversationlist-item-lastmsg').innerText(), /近期体验反馈整理 · 王宜林: 最近聚合验收：子区新消息/);
  assert.equal(await page.locator('.wk-conversationlist-item h3').filter({hasText: '近期体验反馈整理'}).count(), 0);
  await tabs.getByRole('tab', {name: '主聊天'}).click();
  assert.doesNotMatch(await page.locator('.ch-main__body').innerText(), /最近聚合验收：子区新消息/, '主群消息流不混入子区消息');
  await tabs.getByRole('tab', {name: '近期体验反馈整理'}).click();
  assert.match(await page.locator('.ch-main__body').innerText(), /最近聚合验收：子区新消息/, '子区保留自己的消息');
  await page.emulateMedia({reducedMotion: 'reduce'});
  await tabs.getByRole('tab', {name: '主聊天'}).click();
  assert.equal(await tabs.getByRole('tab', {name: '主聊天'}).getAttribute('aria-selected'), 'true');
  await page.emulateMedia({reducedMotion: 'no-preference'});
  await page.setViewportSize({width: 900, height: 800});
  await page.getByRole('heading', {name: 'IM 气泡验证', exact: true}).click();
  await tabs.getByRole('tab', {name: '05 消息操作演示'}).click();
  await page.waitForFunction(() => {
    const nav = document.querySelector('.eva-recent-topic-tabs'), active = nav.querySelector('[role="tab"][aria-selected="true"]');
    const a = active.getBoundingClientRect(), b = nav.getBoundingClientRect();
    return a.left >= b.left - 1 && a.right <= b.right + 1;
  });
  for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowLeft');
  await page.keyboard.press('Enter');
  assert.equal(await tabs.getByRole('tab', {name: '主聊天'}).getAttribute('aria-selected'), 'true', '键盘可回到主聊天');
  await page.getByRole('button', {name: '关注', exact: true}).click();
  assert.equal(await tabs.count(), 0, '关注不接入最近的群内导航');
  await page.getByRole('button', {name: '最近', exact: true}).click();
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
}
