import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';
import {fileURLToPath} from 'node:url';

test('Edge：描述和评论中的任务引用在同一抽屉打开并可返回',async()=>{
  const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch(process.platform==='darwin'?{channel:'msedge'}:{});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:600}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/#/collab?evaProject=prod&evaTab=tasks&evaTask=SC-103`);
    const title=page.locator('.loop-idp__title:visible');
    await title.waitFor();
    assert.equal(await title.inputValue(),'处理关键供应商来料质量异常');
    const descriptionLink=page.locator('.loop-idp__desc [data-eva-task-link="SC-105"]');
    await descriptionLink.waitFor();
    assert.equal(await descriptionLink.textContent(),'SC-105  评估下月KD排产与齐套风险');
    const commentLink=page.locator('.loop-cmt__body [data-eva-task-link="SC-105"]:visible');
    await commentLink.waitFor();
    const linkDecorations=await Promise.all([descriptionLink,commentLink].map(link=>link.evaluate(el=>getComputedStyle(el).textDecorationLine)));
    assert.deepEqual(linkDecorations,['underline','underline'],'描述与评论中的任务链接使用一致的下划线');
    const draft=page.locator('.loop-composer__editor [contenteditable="true"]:visible');
    await draft.fill('待确认放行结论后再更新排产。');
    await descriptionLink.click();
    await title.waitFor();
    assert.equal(await title.inputValue(),'评估下月KD排产与齐套风险');
    assert.equal(await page.locator('.collab-route-right.eva-route-drawer').count(),1,'只保留一个任务抽屉');
    assert.equal(page.url().includes('evaTask=SC-103'),true,'浏览器路由仍指向入口任务');
    const close=page.getByRole('button',{name:'关闭任务详情'});
    assert.equal(await close.getAttribute('data-eva-tooltip'),null,'关闭按钮不显示重复提示');
    const back=page.getByRole('button',{name:'返回跳转前的任务'});
    await back.hover();
    const tooltip=page.getByRole('tooltip').getByText('返回跳转前的任务',{exact:true});
    await tooltip.waitFor();
    await page.mouse.move(0,0);
    await tooltip.waitFor({state:'hidden'});
    await back.focus();
    await tooltip.waitFor();
    assert.equal(await back.getAttribute('title'),null,'返回图标不使用原生浏览器提示');
    await back.click();
    assert.equal(await title.inputValue(),'处理关键供应商来料质量异常');
    assert.equal(await draft.innerText(),'待确认放行结论后再更新排产。','返回后保留未发送评论');
    await commentLink.scrollIntoViewIfNeeded();
    const sourceScroll=await page.locator('.loop-idp__main:visible').evaluate(el=>el.scrollTop);
    assert.ok(sourceScroll>0,'评论位于滚动区域内');
    await commentLink.click();
    assert.equal(await title.inputValue(),'评估下月KD排产与齐套风险');
    await page.getByRole('button',{name:'返回跳转前的任务'}).click();
    assert.equal(await title.inputValue(),'处理关键供应商来料质量异常');
    assert.ok(Math.abs(await page.locator('.loop-idp__main:visible').evaluate(el=>el.scrollTop)-sourceScroll)<3,'返回后恢复原任务评论位置');
    const restrictedLink=page.locator('.loop-cmt__body [data-eva-task-link="ZY-101"]:visible');
    const permittedLink=page.locator('.loop-cmt__body [data-eva-task-link="EVA-102"]:visible');
    await restrictedLink.waitFor();
    await permittedLink.waitFor();
    assert.equal(await restrictedLink.textContent(),'ZY-101  复核交互方案中的任务跳转边界');
    assert.equal(await permittedLink.textContent(),'EVA-102  验证分享链接与来源群权限隔离');
    await restrictedLink.click();
    await page.getByText('你不是该任务所属项目的成员，无法查看任务').waitFor();
    assert.equal(await title.inputValue(),'处理关键供应商来料质量异常','无权限时留在 SC-103');
    await permittedLink.click();
    await page.waitForURL(/evaProject=official.*evaTask=official-102/);
    await page.waitForFunction(()=>Array.from(document.querySelectorAll('.loop-idp__title')).some(el=>el.getClientRects().length&&el.value==='验证分享链接与来源群权限隔离'));
    assert.equal(await title.inputValue(),'验证分享链接与来源群权限隔离');
    assert.deepEqual(errors,[]);
  }finally{
    await browser.close();
    await new Promise(resolve=>server.close(resolve));
  }
});
