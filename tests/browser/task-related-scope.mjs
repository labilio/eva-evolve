import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright';
import {createServer} from '../../tools/serve.mjs';
import {fileURLToPath} from 'node:url';
test('Edge: project task scopes compose with filters and persist independently of view',async()=>{
 const server=createServer(fileURLToPath(new URL('../../dist',import.meta.url)));
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const origin=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch({channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).origin===origin?r.continue():r.abort());
  await page.goto(origin+'/#/collab?evaProject=prod');await page.locator('.loop-board').waitFor();
  const select=async name=>{await page.getByRole('button',{name,exact:true}).click();await page.waitForFunction(name=>document.querySelector('[aria-label="任务范围"] [aria-pressed="true"]')?.textContent===name,name);};
  await select('我参与的');
  await page.screenshot({path:'/tmp/eva-scope-chips.png'});
  assert.equal(await page.locator('.eva-task-filter-chip').count(),0);
  await page.waitForFunction(()=>!document.querySelector('.loop-board')?.textContent.includes('SC-126'));
  assert.match(await page.locator('.loop-board').innerText(),/SC-130/);assert.match(await page.locator('.loop-board').innerText(),/SC-137/);
  await select('全部任务');await page.getByText('SC-126',{exact:true}).waitFor();
  assert.equal(await page.getByRole('checkbox',{name:'只看未读',exact:true}).count(),0);
  await select('我负责的');await page.waitForFunction(()=>!document.querySelector('.loop-board')?.textContent.includes('SC-130'));
  await select('我参与的');
  await page.getByRole('button',{name:'任务视图：看板'}).click();await page.getByRole('menuitem',{name:'表格',exact:true}).click();
  await page.locator('.eva-task-table').waitFor();
  await page.reload();await page.locator('.eva-task-table').waitFor();
  assert.equal(await page.getByRole('button',{name:'我参与的',exact:true}).getAttribute('aria-pressed'),'true');
  await page.locator('.loop-toolbtn').filter({hasText:'筛选'}).click();
  const panel=page.locator('.loop-filter-panel');
  assert.match(await panel.getByLabel('任务范围',{exact:true}).innerText(),/我参与的/);
  await panel.getByLabel('任务范围',{exact:true}).click();await page.getByRole('option',{name:'我负责的',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="任务范围"] [aria-pressed="true"]')?.textContent==='我负责的');
  await page.waitForFunction(()=>!document.querySelector('.eva-task-table')?.textContent.includes('SC-130'));
  await panel.getByLabel('任务范围',{exact:true}).click();await page.getByRole('option',{name:'我参与的',exact:true}).click();
  await panel.locator('.semi-select').nth(1).click();
  await page.getByRole('option',{name:'进行中',exact:true}).click();await panel.locator('.loop-filter-panel__head').click();
  await page.waitForFunction(()=>document.querySelector('.eva-task-filter-chips')?.textContent.includes('进行中'));
  await page.locator('.loop-filter-panel__clear').click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="任务范围"] [aria-pressed="true"]')?.textContent==='全部任务');
  await panel.getByLabel('任务范围',{exact:true}).click();await page.getByRole('option',{name:'我参与的',exact:true}).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'任务视图：表格'}).click();await page.getByRole('menuitem',{name:'层级',exact:true}).click();await page.locator('.eva-issue-hierarchy').waitFor();
  assert.doesNotMatch(await page.locator('.eva-issue-hierarchy').innerText(),/SC-126/);
  await page.goto(origin+'/#/collab?evaProject=official');await page.locator('.eva-issue-hierarchy').waitFor();
  assert.doesNotMatch(await page.locator('.eva-issue-hierarchy').innerText(),/SC-126|SC-130|SC-137/);
  await page.goto(origin+'/#/collab?evaProject=prod');await page.locator('.eva-issue-hierarchy').waitFor();
  assert.equal(await page.getByRole('button',{name:'我参与的',exact:true}).getAttribute('aria-pressed'),'true');
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(r=>server.close(r));}
});
